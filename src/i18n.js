import { cookie } from './auth.js';

export const LANGS = { ko: '한국어', en: 'English', ja: '日本語', zh: '中文' };
export const LOCALES = { ko: 'ko-KR', en: 'en-US', ja: 'ja-JP', zh: 'zh-CN' };

// 접속 국가(CDN 이 붙여 주는 헤더) → 언어. 여기에 없는 나라는 브라우저 언어 설정을 따른다
const COUNTRY_LANG = { KR: 'ko', KP: 'ko', JP: 'ja', CN: 'zh', TW: 'zh', HK: 'zh', MO: 'zh' };

function fromAcceptLanguage(header) {
  const prefs = String(header || '').split(',').map((part) => {
    const [tag, ...params] = part.trim().split(';');
    const q = Number(params.map((p) => p.trim()).find((p) => p.startsWith('q='))?.slice(2));
    return { code: tag.trim().toLowerCase().split('-')[0], q: Number.isNaN(q) ? 1 : q };
  }).filter((p) => p.code && p.q > 0).sort((a, b) => b.q - a.q);
  return prefs.find((p) => LANGS[p.code])?.code || '';
}

// 우선순위: 직접 고른 언어(쿠키) > 접속 국가 > 브라우저 언어 > 영어
export function detectLang(req) {
  const picked = cookie(req, 'lang');
  if (LANGS[picked]) return picked;
  const country = String(req.headers['x-vercel-ip-country'] || req.headers['cf-ipcountry'] || '').toUpperCase();
  return COUNTRY_LANG[country] || fromAcceptLanguage(req.headers['accept-language']) || 'en';
}

export const tr = (lang) => (s, vars) => {
  const out = (DICT[lang]?.[s]) ?? s;
  return vars ? out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : out;
};

export function langMiddleware(req, res, next) {
  req.lang = detectLang(req);
  req.t = tr(req.lang);
  res.set('Vary', 'Cookie, Accept-Language');
  next();
}

// /lang/en 처럼 직접 고르면 쿠키에 기억하고 보던 페이지로 돌아간다
export function langRoute(req, res) {
  if (LANGS[req.params.code]) res.cookie('lang', req.params.code, { sameSite: 'lax', maxAge: 365 * 864e5 });
  let back = '/';
  try {
    const u = new URL(req.headers.referer || '/', 'http://x');
    if (u.host === 'x' || u.host === req.headers.host) back = u.pathname + u.search;
  } catch { /* 잘못된 Referer 는 홈으로 */ }
  res.redirect(back.startsWith('//') ? '/' : back);
}

